// Package schema 定义框架各模块共享的"公共契约"类型。
//
// 为什么需要这个包？
// agent / llm / tool / memory 四个模块之间需要传递数据（对话消息、
// 工具描述、Agent 配置）。如果各模块各自定义结构，它们互相调用时就
// 必须做类型转换，一旦某处结构调整就会波及所有模块。本包是唯一的
// 类型契约来源：所有模块统一 import schema 中定义的类型，保证
// "说同一种语言"。
//
// 设计原则：
//  1. 零依赖：本包只依赖标准库，不 import 框架内任何其他包。
//     因此它永远不会反向依赖其他模块，是依赖图的"根"。
//  2. 纯数据：本包只定义数据结构与基础校验，不含业务逻辑。
//  3. JSON 友好：所有类型标注 json tag，因为 Agent 配置、工具描述
//     都要序列化为 JSON 与 LLM 交互（LLM 只认 JSON 协议）。
//
// 为后期演进预留的扩展点：
//   - Message.Content 目前是纯文本；如需支持多模态（图片/音频），
//     可扩展为内容块数组，不影响已有调用方。
//   - PermissionLevel 已为工具安全分级预留（L0~L3）；高级别工具
//     （执行脚本等）的强制确认与沙盒执行器在 P4 由宿主层实现。
//   - Skill（一组工具的打包能力）与 MCP（工具标准接入协议）属于
//     上层能力，在 P2/P3 引入；本包保证 ToolSchema 可被它们复用。
